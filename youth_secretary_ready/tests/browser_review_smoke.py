"""Human-review simulation UI: historical facts must not create approved tasks."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto('http://127.0.0.1:8000/lab',wait_until='networkidle')
    page.locator('[data-persona="unemployed"]').click()
    page.wait_for_function("!document.querySelector('main').inert")
    page.locator('[data-extrafact="application_date"]').fill('2026-05-06')
    page.locator('[data-extrafact="benefit_history_complete"]').select_option('true')
    page.locator('.historypanel > summary').click()
    page.locator('#addHistory').click()
    row=page.locator('[data-history-row]')
    row.locator('[data-history="start"]').fill('2026-03-01')
    row.locator('[data-history="end"]').fill('2026-05-06')
    row.locator('[data-history="ongoing"]').select_option('false')
    page.locator('#saveFacts').click()
    page.wait_for_function("!document.querySelector('main').inert")
    page.get_by_text('공식 정책 초안 · 검수 전 판별 제외',exact=True).click()
    card=page.locator('[data-review-code="seoul_rent_2026"]')
    card.get_by_text('가상 조건으로 규칙 검토하기 (저장 없음)',exact=True).click()
    card.locator('[data-review-at]').fill('2026-05-06T12:00')
    card.locator('[data-review-run]').click()
    result=card.locator('[data-review-result]')
    finding=result.locator('.finding').filter(has_text='서울시 청년수당의 지원 대상 기간')
    expect(finding).to_contain_text('제한 조건 해당')
    expect(page.locator('#savedTasks')).to_contain_text('아직 승인해 저장한 작업이 없어')
    row.locator('[data-history="end"]').fill('2026-05-05')
    page.locator('#saveFacts').click()
    expect(result).to_contain_text('다시 검토')
    card.locator('[data-review-run]').click()
    expect(finding).to_contain_text('해당 규칙 통과')
    expect(result).to_contain_text('확인 필요')
    card.locator('[data-review-at]').fill('2026-05-19T18:00')
    card.locator('[data-review-run]').click()
    expect(result).to_contain_text('기간: 접수 종료')
    page.reload(wait_until='networkidle')
    expect(page.locator('[data-extrafact="application_date"]')).to_have_value('2026-05-06')
    expect(page.locator('[data-history="end"]')).to_have_value('2026-05-05')
    page.locator('.historypanel > summary').click()
    page.get_by_text('공식 정책 초안 · 검수 전 판별 제외',exact=True).click()
    card.get_by_text('가상 조건으로 규칙 검토하기 (저장 없음)',exact=True).click()
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+1')
    card.screenshot(path=str(BASE/'.local'/'browser-review.png'))
    assert not errors,errors
    print(json.dumps({'passed':True,'history_saved':True,'draft_not_saved_as_tasks':True,'cutoff_verified':True,'page_errors':errors}))
    browser.close()
